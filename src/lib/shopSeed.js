/* The bundled Shop catalog (lib/shop.js + src/config/affiliates.json + shop-reviewed.json) in the partner portal's shape
   (docs/plans/partner-portal.md Task 1): the backend's shop module imports it as published items on its first start with
   an empty store (backend/config/shop-seed.json, written by `npm run shop:seed`; shopSeed.test.mjs fails when that
   file is out of date). Pure: the config objects are passed in. */
import { SHOP_ITEMS, BRANDS, BRAND_HUE, monogram, itemSources, linkFor, priceFor } from "./shop.js";

export const brandId = (name) => String(name || "").toLowerCase().normalize("NFKD").replace(/[^a-z0-9]+/g, "-").replace(/^-+|-+$/g, "").slice(0, 40) || "item";

export function buildSeed({ affiliates = {}, signed = [] } = {}) {
  const names = [...new Set(SHOP_ITEMS.map((i) => i.brand))];
  const brands = names.map((name) => {
    const b = BRANDS[name] || {};
    const first = SHOP_ITEMS.find((i) => i.brand === name);
    return { id: brandId(name), name, monogram: monogram(name), hue: BRAND_HUE[name] || null, tag: b.tag || "", about: b.about || "", website: new URL(first.url).origin + "/", imageId: null };
  });
  const products = SHOP_ITEMS.map((i) => {
    const link = linkFor(i, affiliates);
    return {
      id: i.id, brandId: brandId(i.brand), name: i.name, covers: i.covers || "", description: "", availability: i.avail || "online",
      price: priceFor(i, affiliates) || "", url: i.url, affiliateUrl: link.affiliate ? link.href : "", imageId: null,
      art: i.art || null,
      categories: [i.category, ...(i.also || [])], stages: [...i.stages], modules: [...i.modules], kind: i.kind || null,
      why: i.why || "", evidence: i.tone ? { tone: i.tone, label: i.ev } : null, sources: itemSources(i),
      clinicianStatus: Array.isArray(signed) && signed.includes(i.id) ? "signed" : "awaiting",
    };
  });
  return { _readme: "Generated by `npm run shop:seed` from src/lib/shop.js and src/config/*.json. Do not edit by hand: the backend's shop module imports it once, on a first start with an empty store; after that, edit in the partner portal.", brands, products };
}
