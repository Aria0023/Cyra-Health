/* Prints docs/plans/website-claims.md: every sentence, label and alt text the website shows, word for word, with the
   app or backend file that makes it true (docs/plans/website.md: the eval needs this list). The words come from the
   pages' own register (site/pages/copy.mjs), so the list cannot miss a sentence a page shows.
     node site/build/claims.mjs            writes the file
     node site/build/claims.mjs --check    exits 1 if the committed file is out of date (src/lib/site.test.mjs does the same) */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { loadAppData, ROOT } from "./app-data.mjs";
import { renderPages } from "./site.mjs";
import { LABEL } from "../pages/copy.mjs";

export const CLAIMS_FILE = path.join(ROOT, "docs", "plans", "website-claims.md");
const cell = (s) => String(s).replace(/\|/g, "\\|");

/** The markdown for the pages as rendered from `d` (the app's data with the build's default environment). */
export function claimsMarkdown(d) {
  const pages = renderPages(d);
  const out = [
    "# The website's public claims, and what makes each one true",
    "",
    "Generated by `node site/build/claims.mjs` from the pages themselves (`site/pages/*.mjs` register every string they show).",
    "Do not edit by hand: `npm run test:unit` fails when this file and the pages differ. It is built with no store links, no",
    "support address and no site address set (the repository's defaults); with those set, the buttons and links named in",
    "`site/pages/` replace the \"Coming soon\" lines and add the address, and nothing else changes.",
    "",
    "- **Words**: exactly what a visitor reads (or a screen reader says, for alt text and labels).",
    "- **Made true by**: the app, backend or site file that says or does it. \"label\" marks a name, heading or link text",
    "  that claims nothing by itself.",
    "- A sentence taken from the app is the app's own string, read at build time (`site/build/app-data.mjs`), so it changes",
    "  when the app changes.",
    "",
  ];
  for (const p of pages) {
    const seen = new Set();
    const rows = p.claims.filter((c) => { const k = `${c.text}\u0000${c.source}`; if (seen.has(k)) return false; seen.add(k); return true; });
    out.push(`## /${p.rel === "index.html" ? "" : p.rel.replace(/index\.html$/, "")}`, "", `${rows.filter((r) => r.source !== LABEL).length} claims, ${rows.filter((r) => r.source === LABEL).length} labels.`, "", "| Words | Made true by |", "| --- | --- |");
    for (const r of rows) out.push(`| ${cell(r.text)} | ${cell(r.source)} |`);
    out.push("");
  }
  return out.join("\n");
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const md = claimsMarkdown(await loadAppData());
  if (process.argv.includes("--check")) {
    const have = fs.existsSync(CLAIMS_FILE) ? fs.readFileSync(CLAIMS_FILE, "utf8") : "";
    if (have !== md) { console.error("[solia] docs/plans/website-claims.md is out of date: run node site/build/claims.mjs"); process.exit(1); }
    console.log("[solia] docs/plans/website-claims.md is up to date");
  } else { fs.writeFileSync(CLAIMS_FILE, md); console.log(`[solia] wrote ${path.relative(ROOT, CLAIMS_FILE)}`); }
}
